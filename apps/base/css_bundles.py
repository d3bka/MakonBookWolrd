"""Concatenated stylesheet bundles for the student workspace shell.

The shell used to link ~20 versioned stylesheets one by one. Each bundle is the
exact concatenation, in the original cascade order, of a run of files that were
always loaded back to back — so rendering is identical while the browser makes
3 requests instead of 20.

Edit the SOURCE files, then run ``python manage.py build_css_bundles``.
``apps/base/test_css_bundles_v69.py`` fails if a bundle is out of date.
Source files stay in place: the staff shell still links some of them directly.
"""
from pathlib import Path

from django.conf import settings

CSS_DIR = Path(settings.BASE_DIR) / "static" / "assets" / "css"

BUNDLES = {
    # linked before the page's own {% block student_workspace_style %}
    "student-shell-base.bundle.css": (
        "student-workspace-v50.css",
        "gamification-v52.css",
        "student-workspace-v523.css",
        "student-workspace-v524.css",
    ),
    # linked right after the page's own styles
    "student-shell-layers.bundle.css": (
        "student-workspace-v525.css",
        "student-workspace-v5261.css",
        "student-workspace-v5262.css",
        "student-workspace-v5263.css",
        "student-workspace-v5264.css",
        "student-workspace-v5265.css",
        "student-workspace-v50210.css",
        "student-workspace-spacing-v5266.css",
        "workspace-section-reset-v69.css",
        "student-speed-v554.css",
        "student-world-upcoming-v5571.css",
        "makon-prototype-merge-v60.css",
    ),
    # {% block workspace_final_styles %} — last in <head>
    "student-shell-final.bundle.css": (
        "makon-ui-v62.css",
        "makon-dashboard-prototype-v66.css",
        "makon-unified-workspace-v661.css",
        "makon-workspace-search-v67.css",
        "makon-dashboard-readability-v662.css",
    ),
}


def render_bundle(name):
    parts = [
        f"/* {name} — GENERATED by `manage.py build_css_bundles`; do not edit.\n"
        f"   Sources, in cascade order: {', '.join(BUNDLES[name])} */\n"
    ]
    for source in BUNDLES[name]:
        text = (CSS_DIR / source).read_text(encoding="utf-8")
        parts.append(f"\n/* ==== {source} ==== */\n{text.rstrip()}\n")
    return "".join(parts)


def bundle_for(source):
    """Name of the bundle that ships ``source`` (used by template contract tests)."""
    for name, sources in BUNDLES.items():
        if source in sources:
            return name
    raise KeyError(f"{source} is not in any student shell bundle")
